// This class takes care of the communication between Python and the ORCHESTRA C++ solver
// 
// The initialise method is called once and initialises the solver (calculator) with an external chemistry input file, and the input and output variables
// After initialisation the set_and_calculate_single/multi functions can be used repeatedly to perform calculations on the given cells with the given input variable values
// A vector with selected output variables is returned as result
//
// Version 2025
// Authors: Guido de Zeeuw, Casper Groot, Hans Meeussen
//
// Version 2026, October, Hans Meeussen
// - added alternative single/multi set_and_calculate functions that avoid copying and creating new output vectors by passing references to numpy arrays
//   this is much faster, especially for multithreaded large chemical systems
// - added a function to stop the nodeprocessor and the processing threads (that are kept alive between calls)


class ORCHESTRA {
public:
    NodeType nodeType;          
    Calculator* calculator;         //calculator POINTER object
    StopFlag* stopFlag;             //stopflag POINTER object
    std::vector<Node*>* theNodes;   //vector containing all nodes
    vector<int> IN_index;           //vector listing the indices of the Input variables
    vector<int> OUT_index;          //vector listing the indices of the Output variables
    NodeProcessor* np = NULL;       // used for parallel processing
    
   
    void initialise(std::string inputfile, int nrCells, vector<std::string> input, vector<std::string> output){
    
        // this function creates the calculator & node objects that will be used in the subsequent calculations.
        // as the objects are specified within the ORCHESTRA C++ class (see above), they are "remembered" when calling
        // them in the calculate function.

        //create stopFlag
        stopFlag = new StopFlag();
        
        //create calculator object
        calculator = new Calculator(inputfile);

        //base nodeType on calculator object
        nodeType.useGlobalVariablesFromCalculator(calculator);
               
        //loop over input parameters and add to IO
        //cout << "testing:" << endl;
        for (int n=0 ; n< input.size(); n++){
            nodeType.addVariable(input[n], 0, false, "test");
        };

        //loop over output parameters and add to IO
        for (int n =0 ; n<output.size(); n++){
            nodeType.addVariable(output[n], 0, false, "test");
        };

        // Indices for faster access should be generated by the NodeType object, as the nodeType uses negative indices for static variables
        // Two index vectors  are madee, one for input and one for output variables

        // for INPUT:
        for (int n =0 ; n< input.size(); n++) {
            IN_index.push_back(nodeType.index(input[n]));
            cout << nodeType.index(input[n]) << ":" << input[n] << endl;
        };

        //and for OUTPUT:
        for (int n =0 ; n< output.size(); n++){
            OUT_index.push_back(nodeType.index(output[n]));
            cout << nodeType.index(output[n]) << ":" << output[n] << endl;
        };              

        //creating first node object
        Node node1(&nodeType); 
        
        //cloning the nodes and add them to a nodes-list
        theNodes = new std::vector<Node*>;
        for (int n=0; n<nrCells;n++){
            Node* tmpNode = node1.clone(); //we copy the first node
            theNodes->push_back(tmpNode);
        };
	
	
//        IO::println("Initialisation Completed! the following IO parameters will be used:");

 //       //at the end write all IO variables for the first node.
 //       for (int n = 0; n < nodeType.getNrVars(); n++) {
 //           cout<< n << " : " << nodeType.getName(n)<< " : "<<   theNodes->at(0)->getvalue(n)  <<endl;
//		};
    };


    // This version passes references to the input and output arrays, so no copying involved
    void set_and_calculate_single_2(py::array_t<double>& inp, py::array_t<double>& outp) {

        auto input = inp.unchecked<1>();
        auto output = outp.mutable_unchecked<1>();

        //change values based on input list
        for (int m = 0; m < input.shape(0); m++) {
            theNodes->at(0)->setValue(IN_index[m], input[m]);
        };

        // call the solver for the node 
        bool success = calculator->calculate(theNodes->at(0), stopFlag);

        // copy the results back from the node to the output vector
        for (pybind11::ssize_t m = 0; m < output.shape(0); ++m) {
            output(m) = theNodes->at(0)->getvalue(OUT_index[m]);
        }
    };

    // This version passes references to the input and output arrays, so no copying involved
    void set_and_calculate_multi_2(py::array_t<double> inp, int nrThreads, int memoryOption, py::array_t<double>& outp){
        auto input  = inp.unchecked<>();         
        auto output = outp.mutable_unchecked<>();

        for (pybind11::ssize_t n = 0; n < theNodes->size(); ++n) { 
            for (pybind11::ssize_t m = 0; m < IN_index.size(); ++m) {
                theNodes->at(n)->setValue(IN_index[m], input(n, m));
            }
        }
       
        // we intialise the nodeprocessor only once. We should also destroy it after use!
        // The number of threads is determined when nodeprocessor is created at the first call
        if (np == NULL) {
            cout << "C++ node processor was created, please call solver.stop() after use." << "\n";
            np = new NodeProcessor(calculator, nrThreads, stopFlag, theNodes);
        }

        // process the nodes in parallel
        np->processNodes(theNodes, memoryOption);

        for (pybind11::ssize_t n = 0; n < theNodes->size(); ++n) {
            for (pybind11::ssize_t m = 0; m < OUT_index.size(); ++m) {
                output(n,m) = theNodes->at(n)->getvalue(OUT_index[m]); 
            }
        }
    };

    void stop() {
        if (np != NULL) {
            np->pleaseStop();
            delete np;
        }
        cout<<"C++ node processor was stopped." << "\n";

    }
    
    // we should create a destructor for the following objects:
    // Calculator* calculator;         
    // StopFlag* stopFlag;             
    // std::vector<Node*>* theNodes;  


    //
    // This methods is still here for backward compatibility.
    // 
    py::array_t<double> set_and_calculate_single(vector<double> I_values) {

        // copy the input values to the node, and use the variable index for this 
        for (int m = 0; m < IN_index.size(); m++) {
            theNodes->at(0)->setValue(IN_index[m], I_values[m]);
        };

        // call the solver for the node 
        bool success = false;
        success = calculator->calculate(theNodes->at(0), stopFlag);

        // copy the results back from the node to the output vector
        vector<vector<double>> O_values(theNodes->size(), vector<double>(OUT_index.size())); //make output vector
        for (int m = 0; m < OUT_index.size(); m++) {
            O_values[0][m] = theNodes->at(0)->getvalue(OUT_index[m]);
        };

        return py::cast(O_values); //return list with output values
    };


    //
    // This methods is still here for backward compatibility.
    // 

    py::array_t<double> set_and_calculate_multi(vector<vector<double>> I_values, int nrThreads, int memoryOption) {

        //change values based on input list
        for (int n = 0; n < theNodes->size(); n++) {
            for (int m = 0; m < IN_index.size(); m++) {
                theNodes->at(n)->setValue(IN_index[m], I_values[n][m]);
            };
        };

        // parallel version
        // we intialise the nodeprocessor only once
        if (np == NULL) {
            np = new NodeProcessor(calculator, nrThreads, stopFlag, theNodes); // 8 threads)
        }

        // process the nodes in parallel
        np->processNodes(theNodes, memoryOption);

        //make output vector
        vector<vector<double>> O_values(theNodes->size(), vector<double>(OUT_index.size())); //make output vector
        for (int n = 0; n < theNodes->size(); n++) {
            for (int m = 0; m < OUT_index.size(); m++) {
                O_values[n][m] = theNodes->at(n)->getvalue(OUT_index[m]);
            };
        };

        return py::cast(O_values); //return list with output values
    };





};

//HERE WE MAKE THE WRAPPER WITH PYBIND11
PYBIND11_MODULE(PyORCHESTRA, m) {
    py::class_<ORCHESTRA>(m, "ORCHESTRA") //define class name
        .def(py::init<>())
        .def("initialise", &ORCHESTRA::initialise) //refer to function initialise
        .def("set_and_calculate_single", &ORCHESTRA::set_and_calculate_single)
        .def("set_and_calculate_single_2", &ORCHESTRA::set_and_calculate_single_2)
        .def("set_and_calculate_multi", &ORCHESTRA::set_and_calculate_multi)
        .def("set_and_calculate_multi_2", &ORCHESTRA::set_and_calculate_multi_2)
        .def("stop", &ORCHESTRA::stop);
};
        


